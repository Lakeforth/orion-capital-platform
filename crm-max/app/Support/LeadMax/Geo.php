    private static ?array $index = null;

    /** @return array{name: string, code: ?string, continent: ?string} */
    public static function find(?string $country): array
    {
        $name = trim((string) $country);
        if ($name === '') {
            return ['name' => 'Unknown', 'code' => null, 'continent' => null];
        }
        self::$index ??= collect(self::COUNTRIES)->mapWithKeys(fn ($row, $key) => [mb_strtolower($key) => $key])
            ->merge(collect(self::COUNTRIES)->mapWithKeys(fn ($row, $key) => [$row[0] => $key]))->all();
        $lower = mb_strtolower($name);
        $key = self::$index[mb_strtolower(self::ALIASES[$lower] ?? $name)] ?? null;
        if (! $key) {
            return ['name' => $name, 'code' => null, 'continent' => null];
        }

        return ['name' => $name, 'code' => self::COUNTRIES[$key][0], 'continent' => self::COUNTRIES[$key][1]];
    }

    public static function continent(?string $country): ?string
    {
        return self::find($country)['continent'];
    }

    public static function flag(?string $country): ?string
    {
        $code = self::find($country)['code'];

        return $code ? asset('images/flags/'.$code.'.svg') : null;
    }
