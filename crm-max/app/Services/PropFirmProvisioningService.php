<?php

namespace App\Services;

use App\Mail\ChallengeStartedMail;
use App\Models\Challenge;
use App\Models\ChallengePlan;
use App\Models\TradingAccount;
use App\Models\User;
use Illuminate\Support\Facades\Mail;

class PropFirmProvisioningService
{
    /**
     * Core Challenge + TradingAccount creation, shared by the client
     * self-purchase flow (Api\PropFirmController::storeChallenge) and the
     * admin manual-grant flow (Admin\PropFirmController::challengesStore).
     * Pricing, promo/addon resolution, balance checks, and the debit itself
     * are each caller's own concern -- by the time this runs, the caller has
     * already decided what fee (if any) applies and collected it. This only
     * does the DB-write part that's identical either way. Deliberately does
     * NOT send the "challenge started" email itself, unlike
     * provisionPhaseAccount() below -- callers run this inside their own
     * DB::transaction() (the debit/audit-Transaction still has to happen),
     * and mailing credentials for a challenge that might still roll back
     * would be wrong. Send ChallengeStartedMail yourself, after your
     * transaction commits.
     */
    public function createChallenge(User $user, ChallengePlan $plan, array $addonKeys, ?string $promoCode, ?float $promoDiscountPct, float $feePaid): Challenge
    {
        $firstPhase = $plan->phases()->orderBy('phase_number')->first();

        // company_id set explicitly from the target user rather than relying
        // on BelongsToCompany's auto-assign-from-app('company') -- that
        // binding exists for tenant-resolved client requests but admin
        // routes don't reliably have it (every other admin-side ::create()
        // in this controller passes company_id explicitly too, e.g.
        // PropFirmController::plansStore()), so this needs to work
        // correctly regardless of which context calls it.
        $challenge = Challenge::create([
            'company_id' => $user->company_id,
            'user_id' => $user->id,
            'challenge_plan_id' => $plan->id,
            'status' => 'active',
            'current_phase' => $firstPhase?->phase_number ?? 1,
            'starting_balance' => $plan->account_size,
            'fee_paid' => $feePaid,
            'addons' => $addonKeys,
            'promo_code' => $promoCode,
            'promo_discount_pct' => $promoDiscountPct,
            'started_at' => now(),
            'phase_started_at' => now(),
        ]);

        $account = TradingAccount::create([
            'company_id' => $user->company_id,
            'user_id' => $user->id,
            'account_type' => TradingAccount::TYPE_CHALLENGE,
            'name' => "{$plan->title} Challenge",
            'base_currency' => 'usd',
            'config' => ['challenge_id' => $challenge->id],
            'balance' => $plan->account_size,
        ]);

        $challenge->update(['trading_account_id' => $account->id]);

        return $challenge->fresh(['plan.phases', 'tradingAccount']);
    }

    /**
     * Issue a brand-new TradingAccount (fresh account_id/password/trading_server,
     * auto-generated by TradingAccount::booted()) for the challenge's current
     * phase, deactivate whatever account it previously had, and email the new
     * credentials -- each phase (and the eventual funded account) is meant to
     * be a fully distinct login, not a balance reset on the same account.
     * Historical trades/daily-stats stay correctly attributed to their phase
     * via phase_started_at timestamps, not via which account row they're on,
     * so swapping the account here doesn't disturb evaluation history.
     */
    public function provisionPhaseAccount(Challenge $challenge, float $balance, string $phaseLabel): TradingAccount
    {
        $previousAccount = $challenge->tradingAccount;

        if ($previousAccount) {
            $previousAccount->update(['is_active' => false]);
        }

        $account = TradingAccount::create([
            'user_id' => $challenge->user_id,
            'account_type' => TradingAccount::TYPE_CHALLENGE,
            'name' => "{$challenge->plan->title} - {$phaseLabel}",
            'base_currency' => 'usd',
            'config' => ['challenge_id' => $challenge->id],
            'balance' => $balance,
        ]);

        $challenge->update(['trading_account_id' => $account->id]);

        $user = $challenge->user;

        if ($user) {
            Mail::to($user->email)->send(new ChallengeStartedMail([
                'customerName' => trim("{$user->first_name} {$user->last_name}"),
                'planTitle' => $challenge->plan->title,
                'accountSize' => format_price($balance),
                'phaseLabel' => $phaseLabel,
                'accountId' => $account->account_id,
                'tradingServer' => $account->trading_server,
                'password' => $account->password,
                'startUrl' => config('app.url'),
            ], $challenge->company_id));
        }

        return $account;
    }
}
